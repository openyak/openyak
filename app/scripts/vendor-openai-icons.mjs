#!/usr/bin/env node

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const SOURCE_COMMIT = '0f00143c7a639906f1621fe58e1b6be7b5bea46d'
const ICON_NAMES = [
  'SidebarOpenLeft',
  'ComposeEditSquare',
  'Folder',
  'MagnifyingGlassSearch',
  'Plus',
  'HandRaised',
  'ChevronSmallDown',
  'ArrowUpSm',
  'ArrowDownSm',
  'StopSm',
  'Check',
  'Copy',
  'Regenerate',
  'PlayTriangle',
  'SparkleDouble',
  'SpeedometerLatencySpeed',
  'MemoryFilledSm',
  'DotsHorizontal',
  'ChevronUpDown',
  'Delete',
  'TerminalLg',
  'FileBlank',
  'ChevronRight',
  'X',
  'Paperclip',
  'ImageSquare',
  'Warning',
  'Lightbulb',
  'ShieldLock',
  'Bolt',
  'Desktop',
  'Chat',
  'SettingsCog',
]

const sourceRoot = process.argv[2]
if (!sourceRoot) {
  throw new Error(
    'Usage: node app/scripts/vendor-openai-icons.mjs /path/to/apps-sdk-ui/src/components/Icon/svg',
  )
}

const appRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const outputPath = join(appRoot, 'src/renderer/src/assets/openai-icons.svg')

function jsxToSvg(source, name) {
  const match = source.match(/<svg\b([^>]*)>([\s\S]*?)<\/svg>/)
  if (!match) throw new Error(`Could not find <svg> in ${name}.tsx`)

  const viewBox = match[1].match(/viewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`Could not find viewBox in ${name}.tsx`)

  const body = match[2]
    .replace(/fillRule=/g, 'fill-rule=')
    .replace(/clipRule=/g, 'clip-rule=')
    .replace(/strokeLinecap=/g, 'stroke-linecap=')
    .replace(/strokeLinejoin=/g, 'stroke-linejoin=')
    .replace(/strokeWidth=/g, 'stroke-width=')
    .trim()

  if (/\{[^}]+\}/.test(body)) {
    throw new Error(`Unsupported JSX expression in ${name}.tsx`)
  }

  return `  <symbol id="${name}" viewBox="${viewBox}">\n${body
    .split('\n')
    .map((line) => `    ${line.trim()}`)
    .join('\n')}\n  </symbol>`
}

const symbols = []
for (const name of ICON_NAMES) {
  const source = await readFile(join(resolve(sourceRoot), `${name}.tsx`), 'utf8')
  symbols.push(jsxToSvg(source, name))
}

const sprite = `<!--
  Vendored from OpenAI Apps SDK UI at commit ${SOURCE_COMMIT}.
  Source: https://github.com/openai/apps-sdk-ui/tree/${SOURCE_COMMIT}/src/components/Icon/svg
  License: ./OPENAI-ICONS-LICENSE.txt
  Generated by: app/scripts/vendor-openai-icons.mjs
-->
<svg xmlns="http://www.w3.org/2000/svg">
${symbols.join('\n')}
</svg>
`

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, sprite)
process.stdout.write(`Vendored ${ICON_NAMES.length} official OpenAI icons to ${outputPath}\n`)
